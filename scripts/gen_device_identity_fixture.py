#!/usr/bin/env python3
"""Regenerate protocol/fixtures/device-identity.json — §10.2's local device keys.

    python3 scripts/gen_device_identity_fixture.py > protocol/fixtures/device-identity.json

A THIRD IMPLEMENTATION, like the fixtures beside it, and it is pinning the one thing most likely to
diverge here: **the public keys two runtimes derive from the same private bytes.** Ed25519 has a seed
form and an expanded form; X25519 clamps its scalar. CryptoKit and @noble each do the right thing,
but they are not the same code, and a device whose two runtimes disagree about its own public keys
has a different `device_id` in each — which presents as a grant that verifies everywhere except on
the device it was issued to.

The installation record is LOCAL ONLY and no peer ever parses it, but it is pinned too: the two
implementations must at least agree with themselves across a reinstall.

Stdlib only. NEVER edit a vector by hand to make a suite pass.
"""
import hashlib
import json
import sys

sys.path.insert(0, __file__.rsplit("/", 1)[0])
from e2e_sigs import ed25519_public_key, self_test, x25519_public_key  # noqa: E402


def lp(b: bytes) -> bytes:
    assert len(b) <= 0xFFFF
    return len(b).to_bytes(2, "big") + b


def utf8(s: str) -> bytes:
    return s.encode("utf-8")


def clamp(raw: bytes) -> bytes:
    k = bytearray(raw)
    k[0] &= 248
    k[31] &= 127
    k[31] |= 64
    return bytes(k)


def device(root_id: bytes, signing_pub: bytes, noise_pub: bytes) -> bytes:
    return lp(utf8("rdev-e2e/device/v1")) + root_id + signing_pub + noise_pub


def record(signing_priv: bytes, noise_priv: bytes, seed: bytes) -> bytes:
    return lp(utf8("rdev-e2e/installation/v1")) + signing_priv + noise_priv + seed


ROOT_ID = hashlib.sha256(b"a fixture root").digest()

seeds = [
    ("zeros", bytes(32), bytes(32), bytes(32)),
    ("ones", b"\xff" * 32, b"\xff" * 32, b"\xff" * 32),
    ("counting", bytes(range(32)), bytes(range(32, 64)), bytes(range(64, 96))),
    ("sha", hashlib.sha256(b"signing").digest(), hashlib.sha256(b"noise").digest(),
     hashlib.sha256(b"rendezvous").digest()),
]

cases = []
for name, signing_priv, raw_noise, seed in seeds:
    noise_priv = clamp(raw_noise)
    signing_pub = ed25519_public_key(signing_priv)
    noise_pub = x25519_public_key(noise_priv)
    desc = device(ROOT_ID, signing_pub, noise_pub)
    cases.append({
        "name": name,
        "signing_private_key": signing_priv.hex(),
        "signing_public_key": signing_pub.hex(),
        "noise_private_key_raw": raw_noise.hex(),
        "noise_private_key": noise_priv.hex(),
        "noise_public_key": noise_pub.hex(),
        "rendezvous_seed": seed.hex(),
        "descriptor": desc.hex(),
        "device_id": hashlib.sha256(desc).digest().hex(),
        "record": record(signing_priv, noise_priv, seed).hex(),
    })

# CLAMPING IS INVISIBLE IN THE PUBLIC KEY AND VISIBLE IN THE STORED BYTES. X25519 clamps its scalar
# internally, so an unclamped private key yields the SAME public key — which is why clamping before
# storing is a choice about the record rather than about the cryptography, and why a runtime that
# skipped it would produce a byte-different record that nevertheless works. Pinned so the two
# implementations store the same thing.
for c in cases:
    raw = bytes.fromhex(c["noise_private_key_raw"])
    assert x25519_public_key(raw) == bytes.fromhex(c["noise_public_key"]), \
        "clamping must not change the public key"

doc = {
    "_comment": [
        "Cross-implementation vectors for §10.2's local device keys.",
        "GENERATED BY A THIRD IMPLEMENTATION (stdlib Python; scripts/gen_device_identity_fixture.py),",
        "whose Ed25519 and X25519 are pinned to RFC 8032 §7.1 and RFC 7748 §6.1 before it emits.",
        "",
        "THE POINT IS THE PUBLIC KEYS. Ed25519 has a seed form and an expanded form and X25519 clamps",
        "its scalar; two runtimes that disagree about the public keys a private key implies give the",
        "device a different device_id in each, which presents as a grant that verifies everywhere",
        "except on the device it was issued to.",
        "",
        "record = LP('rdev-e2e/installation/v1') || signing_private || noise_private || seed.",
        "LOCAL ONLY: no peer ever parses it. `noise_private_key_raw` is the unclamped draw and",
        "`noise_private_key` is what is stored; both give the same public key, which is why clamping",
        "before storing is a decision about the record rather than about the cryptography.",
        "",
        "Regenerate with scripts/gen_device_identity_fixture.py; never edit a value by hand."
    ],
    "root_id": ROOT_ID.hex(),
    "cases": cases,
}

if __name__ == "__main__":
    self_test()
    print(json.dumps(doc, indent=1))
