#!/usr/bin/env python3
"""Regenerate protocol/fixtures/pairing-v3.json — the cross-implementation vectors for the v3
one-time pairing derivation (spec section 9.1).

    python3 scripts/gen_pairing_fixture.py > protocol/fixtures/pairing-v3.json

THIS IS A THIRD IMPLEMENTATION, and that is its entire reason for existing. The Swift
(RdevCore.PairingSeed) and TypeScript (protocol/src/pairing-seed.ts) sides each assert against what
this produces, so each agrees with something neither of them wrote. Two implementations that agree
only with each other can be wrong together, and this repo has paid for that before.

Stdlib only (hmac, hashlib, base64, json) on purpose: a dependency here would be a fourth thing that
has to be right, and the point is to owe nothing to the code under test.

NEVER edit a vector by hand to make a suite pass. If a vector is wrong, the derivation in the spec is
wrong, and that is a spec change.
"""
import hmac, hashlib, json, base64

ALPHABET = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789-_"
SALT = b"rdev-e2e/pair/v3"

def extract(salt, ikm):
    return hmac.new(salt, ikm, hashlib.sha256).digest()

def expand(prk, info, length):
    out, t, i = b"", b"", 1
    while len(out) < length:
        t = hmac.new(prk, t + info + bytes([i]), hashlib.sha256).digest()
        out += t; i += 1
    return out[:length]

def b64u(b):
    return base64.urlsafe_b64encode(b).decode().rstrip("=")

def uuid_v4(raw):
    b = bytearray(raw)
    b[6] = (b[6] & 0x0f) | 0x40
    b[8] = (b[8] & 0x3f) | 0x80
    h = b.hex()
    return f"{h[0:8]}-{h[8:12]}-{h[12:16]}-{h[16:20]}-{h[20:32]}"

# **SIXTEEN BYTES, AND THE CARRIER HAS NO PREFIX** (2026-09-15). The seed's only job is the psk's
# resistance to an OFFLINE attack — the XXpsk3 transcript is on the wire, so a recorder can test
# guesses at leisure — and 128 bits is comfortably infeasible for that. 256 was matched to Noise's
# PSK slot rather than to a threat, and cost 25 characters of the thing a person types.
#
# The `ss3.` discriminator is gone with it: nothing else in the product is a bare base64url string,
# the v2 carrier is retired, and a 22-character payload cannot be read as a URL because none of
# `:`, `/`, `?`, `#` or `=` is in the alphabet.
seeds = {
    "all-zero":    bytes(16),
    "counting":    bytes(range(16)),
    "all-ff":      b"\xff" * 16,
    "sha-of-rdev": hashlib.sha256(b"rdev pairing fixture v3").digest()[:16],
}

cases = []
for name, seed in seeds.items():
    prk = extract(SALT, seed)
    cases.append({
        "name": name,
        "seed": seed.hex(),
        "encoded": b64u(seed),
        "code": "".join(ALPHABET[b % 64] for b in expand(prk, b"code", 8)),
        "token": uuid_v4(expand(prk, b"token", 16)),
        "psk": expand(prk, b"psk", 32).hex(),
    })

doc = {
    "_comment": [
        "Cross-implementation vectors for the v3 one-time pairing derivation (spec 9.1).",
        "GENERATED BY A THIRD IMPLEMENTATION (stdlib Python hmac/hashlib) so that the Swift and",
        "TypeScript sides each agree with something neither of them produced. Two implementations",
        "that agree only with each other can be wrong together, and this repo has paid for that.",
        "Regenerate with the script recorded in the commit that introduced this file; do not edit by",
        "hand, and never 'fix' a vector to make a suite pass.",
        "seed/psk are hex; encoded is the out-of-band carrier; code and token are the public values."
    ],
    "salt": "rdev-e2e/pair/v3",
    "alphabet": ALPHABET,
    "cases": cases,
}
print(json.dumps(doc, indent=2))
