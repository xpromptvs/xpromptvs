#!/usr/bin/env python3
"""Regenerate protocol/fixtures/rendezvous-v7.json — the durable-route derivation (spec §9.2).

    python3 scripts/gen_rendezvous_fixture.py > protocol/fixtures/rendezvous-v7.json

A THIRD IMPLEMENTATION, like `gen_pairing_fixture.py` beside it, and deliberately a SEPARATE file
from the pairing one: §9.1 and §9.2 are the same construction under different labels, so a generator
that shared a salt constant between them could not catch the one mistake that matters here —
deriving a durable route under the pairing label, or the reverse. Each script states its own salt.

**THE SALT IS `rdev/rendezvous/v7`.** It is the one label in this protocol that does not carry the
`rdev-e2e` prefix, and it is quoted from the spec. A "tidy-up" to match its neighbours changes every
route ever derived.

Stdlib only. NEVER edit a vector by hand to make a suite pass.
"""
import hashlib
import hmac
import json

ALPHABET = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789-_"
SALT = b"rdev/rendezvous/v7"
PAIRING_SALT = b"rdev-e2e/pair/v3"


def extract(salt: bytes, ikm: bytes) -> bytes:
    return hmac.new(salt, ikm, hashlib.sha256).digest()


def expand(prk: bytes, info: bytes, length: int) -> bytes:
    out, block, counter = b"", b"", 1
    while len(out) < length:
        block = hmac.new(prk, block + info + bytes([counter]), hashlib.sha256).digest()
        out += block
        counter += 1
    return out[:length]


def uuid_v4(raw: bytes) -> str:
    b = bytearray(raw)
    b[6] = (b[6] & 0x0F) | 0x40
    b[8] = (b[8] & 0x3F) | 0x80
    h = b.hex()
    return f"{h[:8]}-{h[8:12]}-{h[12:16]}-{h[16:20]}-{h[20:]}"


def route(seed: bytes):
    prk = extract(SALT, seed)
    return ("".join(ALPHABET[b % 64] for b in expand(prk, b"code", 8)),
            uuid_v4(expand(prk, b"token", 16)))


seeds = {
    "zeros": bytes(32),
    "ones": b"\xff" * 32,
    "counting": bytes(range(32)),
    "sha-of-rdev": hashlib.sha256(b"rdev rendezvous fixture v7").digest(),
}

cases = []
for name, seed in seeds.items():
    code, token = route(seed)
    cases.append({"name": name, "seed": seed.hex(), "rcode": code, "rtoken": token})

# THE CASE THE SEPARATE FILE EXISTS FOR: the same seed under §9.1's label gives a DIFFERENT route.
# A build that derived a durable route under the pairing salt would produce a perfectly well-formed
# code and token, register them, and be unreachable at the address every peer persisted.
_shared = bytes(range(32))
# **§9.1's SEED IS 16 BYTES SINCE 2026-09-15**, §9.2's is still 32 — the durable route is public and
# its length was never about entropy against an offline attack. So the pairing half of this
# comparison takes the first 16 bytes: the point is that one label cannot be mistaken for the other,
# and feeding §9.1 a length it refuses would prove that by accident rather than on purpose.
_pair_seed = _shared[:16]
_prk_pair = extract(PAIRING_SALT, _pair_seed)
cases.append({
    "name": "label-separation",
    "seed": _shared.hex(),
    "rcode": route(_shared)[0],
    "rtoken": route(_shared)[1],
    "pairing_code": "".join(ALPHABET[b % 64] for b in expand(_prk_pair, b"code", 8)),
    "pairing_token": uuid_v4(expand(_prk_pair, b"token", 16)),
    "pairing_seed": _pair_seed.hex(),
    "note": "the first 16 bytes under §9.1's salt: every value must differ",
})

doc = {
    "_comment": [
        "Cross-implementation vectors for the §9.2 durable rendezvous derivation.",
        "GENERATED BY A THIRD IMPLEMENTATION (stdlib Python) so Swift and TypeScript each agree with",
        "something neither wrote.",
        "",
        "rseed  <- random(32)                         persisted WITH the device keys",
        "RPRK   = HKDF-Extract('rdev/rendezvous/v7', rseed)",
        "rcode  = each byte of HKDF-Expand(RPRK, 'code', 8) modulo 64 through the alphabet",
        "rtoken = UUID-format(HKDF-Expand(RPRK, 'token', 16))",
        "",
        "There is NO psk here: a durable route is public by construction, and all the authority is",
        "in the grant chain. The last case pins LABEL SEPARATION against §9.1's derivation.",
        "",
        "Regenerate with scripts/gen_rendezvous_fixture.py; never edit a value by hand."
    ],
    "salt": SALT.decode(),
    "alphabet": ALPHABET,
    "cases": cases,
}
print(json.dumps(doc, indent=1))
