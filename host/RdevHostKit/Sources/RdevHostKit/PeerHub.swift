import Foundation
import LLVCore
import RdevCore

/// Owns one PionPeer per connected client. Registers each peer as an encoder consumer so every
/// encoded frame is fanned out to all clients. Routes signaling (offer/ICE) back through the
/// transport callbacks set by the caller.
/// @unchecked Sendable: the sessions map + stored turn are guarded by `lock`; signaling
/// callbacks arrive on the transport's single receive continuation.
public final class PeerHub: NSObject, @unchecked Sendable {
    private let channelHub: ChannelHub
    private let totalRTPBudgetBps: UInt32
    private let fps: Int
    private let lock = NSLock()
    private var sessions: [String: PionPeer] = [:]
    private var fastConnections: [String: FastClientConnection] = [:]
    private var turn: TurnCreds?

    // Grace-hold state (Phase 3): a peer whose client disconnects is held (not torn down) for a
    // window, in case the client reconnects and can resume the same conversation. All guarded by
    // `lock`, same as `sessions`.
    private var suspended: Set<String> = []          // ids in their grace window
    private var graceTimers: [String: DispatchWorkItem] = [:]
    private let graceQueue = DispatchQueue(label: "rdev.peerhub.grace")
    private let graceMs = 180_000

    // Set after the transport is constructed (the transport's onEvent references the hub).
    // `restart` reflects `PionPeer.consumeRestartFlag()`: false for a fresh `startOffer`, true for
    // the offer generated by `restartIce()` (Task 15) — so the transport can tag `restart:true`.
    public var sendOfferRestart: ((_ sdp: String, _ peer: String, _ restart: Bool) -> Void)?
    var onFastFailure: ((String, Data) -> Void)?
    public var sendIce: ((_ cand: [String: Any], _ peer: String) -> Void)?

    /// `totalRTPBudgetBps` is the bitrate CAP (HostConfig.bitrateCapBps), handed to every session so
    /// the adaptive FlexFEC controller has a budget to divide. Zero while recovery is `nack-rtx`,
    /// which is the default — the engine refuses a non-zero budget outside FlexFEC mode.
    public init(channelHub: ChannelHub, fps: Int = 30, totalRTPBudgetBps: UInt32 = 0) {
        self.channelHub = channelHub; self.fps = fps
        self.totalRTPBudgetBps = totalRTPBudgetBps
        super.init()
    }

    public func configure(turn: TurnCreds) { lock.lock(); self.turn = turn; lock.unlock() }

    /// Build + wire a fresh `PionPeer` for `id`: signaling callbacks, the channel delegate, and the
    /// keyframe-request hook. Shared by `clientJoined` and `rebuildPeer` so both construct a peer
    /// identically. (A real ICE restart, Task 15, does NOT go through `makePeer` — it reuses the
    /// retained `PionPeer` via `restartIce()`.) Does NOT touch `sessions` or start the offer —
    /// callers own placement + when to negotiate.
    private func makePeer(_ id: String) -> PionPeer {
        lock.lock(); let turn = self.turn; lock.unlock()
        // The coordinator is PER PEER because the sequence it validates is per SESSION: one shared
        // across peers would see two controllers' sequences interleave and reject both. It is what
        // enforces monotonicity, idempotence and the tier/bitrate rules; SimManager only applies.
        //
        // BUILT BEFORE THE PEER, because the adaptive controller emits its first update from inside
        // pion_peer_create and requires it to be acknowledged — see PionPeer.onRecoveryPolicy.
        let budget = totalRTPBudgetBps
        let coordinator = CaptureRecoveryBitrateCoordinator { [weak self] mediaBitrateBps in
            guard let self else { throw PeerHubRecoveryError.hostGone }
            guard self.channelHub.applyRecoveryPolicy(
                mediaBitrateBps: UInt32(clamping: mediaBitrateBps), budgetBps: budget)
            else { throw PeerHubRecoveryError.notApplied }
        }
        let peer = PionPeer(
            clientId: id, turn: turn, totalRTPBudgetBps: totalRTPBudgetBps,
            onRecoveryPolicy: { sequence, tier, mediaBitrateBps in
                guard let policy = CaptureFlexFECPolicy(rdevTierWireValue: tier) else { return false }
                do {
                    try coordinator.apply(CaptureRecoveryPolicyUpdate(
                        sequence: sequence, tier: policy,
                        mediaBitrateBitsPerSecond: Int(mediaBitrateBps)))
                    return true
                } catch {
                    print("[bridge] recovery policy \(sequence) rejected: \(error)")
                    return false
                }
            })
        peer.onLocalDescription = { [weak self, weak peer] sdp in
            guard let self, let peer else { return }
            self.sendOfferRestart?(sdp, id, peer.consumeRestartFlag())
        }
        peer.onIceCandidate = { [weak self] c in self?.sendIce?(c, id) }
        peer.delegate = channelHub
        peer.onKeyframeRequest = { [weak self] slot in self?.channelHub.requestKeyframe(clientId: id, slot: slot) }
        peer.onReferenceRecoveryRequest = { [weak self, weak peer] slot, _, intent in
            guard let peer else { return }
            self?.channelHub.requestReferenceRecovery(peer: peer, slot: slot, intent: intent)
        }
        peer.onReferenceSent = { [weak self, weak peer] slot, message in
            guard let peer else { return }
            self?.channelHub.referenceSent(peer: peer, slot: slot, message: message)
        }
        peer.onReferenceWriteFailed = { [weak self, weak peer] slot, metadata in
            guard let peer else { return }
            self?.channelHub.referenceWriteFailed(peer: peer, slot: slot, metadata: metadata)
        }
        peer.onCodecResolved = { [weak self] slot, codec in self?.channelHub.codecResolved(clientId: id, slot: slot, codec: codec) }
        return peer
    }

    /// `claim`: the client is CONNECTING (its join intent) and takes control (`ChannelHub.register`).
    /// `grid`: what it said as it joined (`JoinHello`) — applied once it is registered (and so the driver, if it
    /// claimed) and BEFORE the offer, whose screen is then at that grid (`ChannelHub.applyJoinGrid`).
    public func clientJoined(_ id: String, claim: Bool = false, grid: TermGridSize? = nil) {
        let peer = makePeer(id)
        lock.lock(); sessions[id] = peer; let active = sessions.count; lock.unlock()
        let connection = fastConnection(id)
        connection?.attachMediaPeer(peer)
        channelHub.register(clientId: id, peer: connection ?? (peer as ClientConnection), claim: claim)
        if let grid { channelHub.applyJoinGrid(grid, clientId: id) }
        peer.startOffer()
        print("[PeerHub] client \(id) joined (\(active) active)")
    }

    func fastConnection(_ id: String) -> FastClientConnection? { lock.withLock { fastConnections[id] } }

    func disableFast(_ id: String) {
        let (fast, peer) = lock.withLock { (fastConnections.removeValue(forKey: id), sessions[id]) }
        fast?.close()
        if let peer { peer.delegate = channelHub; channelHub.rebindPeer(clientId: id, peer: peer) }
    }

    /// Install before admission; replacement without retained delivery state deliberately resets the terminal wire.
    func prepareFast(_ id: String, generation: Data) -> FastClientConnection {
        if let existing = fastConnection(id), existing.generation == generation { return existing }
        weak var connection: FastClientConnection?
        let fast = FastClientConnection(clientId: id, generation: generation,
            onOpen: { [weak self] ch in guard let c = connection else { return }; self?.channelHub.connection(c, didOpen: ch) },
            onMessage: { [weak self] ch, bytes in guard let c = connection else { return }; self?.channelHub.connection(c, didReceive: bytes, on: ch) },
            onFailure: { [weak self] reason in
                guard let self, let c = connection, self.fastConnection(id) === c else { return }
                print("[fast] \(id): \(reason)")
                self.onFastFailure?(id, generation)
            })
        connection = fast
        fast.onMediaState = { [weak self] peer, state in self?.channelHub.pionPeer(peer, stateDidChange: state) }
        let (old, peer) = lock.withLock { let old = fastConnections.updateValue(fast, forKey: id); return (old, sessions[id]) }
        old?.close()
        if let peer { fast.attachMediaPeer(peer); channelHub.rebindPeer(clientId: id, peer: fast) }
        return fast
    }

    public func answer(_ sdp: String, from id: String) {
        lock.lock(); let s = sessions[id]; lock.unlock()
        s?.acceptAnswer(sdp)
    }

    public func ice(_ cand: [String: Any], from id: String) {
        lock.lock(); let s = sessions[id]; lock.unlock()
        s?.addIce(cand)
    }

    public func clientLeft(_ id: String) {
        lock.lock(); let s = sessions[id]; sessions[id] = nil; let active = sessions.count; lock.unlock()
        let fast = lock.withLock { fastConnections.removeValue(forKey: id) }; fast?.close()
        if let s { s.close() }   // ChannelHub.unregister drops the delivery sink (it owns videoSlots now)
        // The real teardown (not a transport blip PeerHub itself already holds grace for, see `suspend`/
        // `resume` below). Whether it ends the STREAMS is ChannelHub's call — only the driver leaving
        // with nobody to take over does (`unregister`).
        channelHub.unregister(clientId: id)
        print("[PeerHub] client \(id) left (\(active) active)")
    }

    /// **STOP SHARING: EVERY RELAY CLIENT LEAVES NOW** — each through `clientLeft`, so `ChannelHub`
    /// unregisters it exactly as when it leaves by itself, and one held in its grace window too, its timer
    /// cancelled. Left registered, a relay driver would hold control of the session for the 180 s grace
    /// with nobody able to reach it; the session's other clients (the app's local window) are untouched.
    /// On `graceQueue`, like every other grace decision, so a timer cannot fire into the middle of it.
    public func allClientsLeft() {
        let ids: [String] = graceQueue.sync {
            lock.lock()
            for timer in graceTimers.values { timer.cancel() }
            let ids = Set(sessions.keys).union(suspended)
            graceTimers.removeAll()
            suspended.removeAll()
            lock.unlock()
            return Array(ids)
        }
        // THE DRIVER LEAVES LAST: `ActiveClientTracker.leave` promotes a client only when exactly ONE remains
        // as the driver goes, so a driver leaving early over two others promotes nobody, and the session's
        // socket client is left passive in a driverless session. Set order is random; this is not.
        // ONE partition pass: two filters each asked `isActiveClient`, and an id whose state flipped between
        // them (a claim racing Stop) landed in neither list and never left.
        var passive: [String] = [], active: [String] = []
        for id in ids { if channelHub.isActiveClient(id) { active.append(id) } else { passive.append(id) } }
        let ordered = passive + active
        for id in ordered { clientLeft(id) }
    }

    // MARK: - Grace-hold (Phase 3)
    //
    // A client that drops (transport reconnect in flight) is "suspended" rather than torn down
    // immediately: its PionPeer + ChannelHub state are held for a grace window, so a client that
    // reconnects in time can resume without losing terminal/video state. `graceDecide` (RdevCore) is
    // the pure decision table; PeerHub just holds the timers and drives the resulting actions.
    //
    // CONCURRENCY: the grace STATE MACHINE (suspend / resume / the timer-fired graceExpired) is
    // serialized on the single serial `graceQueue`. `graceExpired` already runs there (it's the
    // `asyncAfter` DispatchWorkItem block); `suspend`/`resume` run their bodies inside
    // `graceQueue.sync { … }`. This makes a timer-fire and a resume MUTUALLY EXCLUSIVE — whichever
    // reaches the queue first runs to completion before the other starts — closing the race where a
    // firing grace timer's teardown and a concurrent `.freshJoin` resume could interleave so that
    // `clientLeft` tore down the freshly-rebuilt peer. `sync` (not `async`) preserves the transport's
    // "onEvent runs to completion before the next receive" ordering. It is deadlock-free: `suspend`/
    // `resume` are only ever called from the transport thread (main.swift onEvent), NEVER from within
    // a `graceQueue` block, and nothing reachable from these bodies (graceExpired→clientLeft,
    // resume→rebuildPeer/clientJoined) re-enters `graceQueue.sync`.
    //
    // The `lock` (NSLock) is still used for the `sessions`/`suspended`/`graceTimers` map ops: it's
    // needed because `clientJoined` (from `.peerJoined`), `answer`, and `ice` run on the transport
    // thread and touch `sessions` cross-thread vs. the graceQueue-serialized paths. `graceQueue`
    // serializes the state machine; `lock` protects individual map access. QUEUE↔LOCK ORDERING:
    // `lock` is only ever acquired *inside* a `graceQueue` block (or on the transport thread, never
    // while entering the queue) — we never hold `lock` across `graceQueue.sync`, so the two can't
    // deadlock against each other.

    /// The transport told us this client's connection dropped. Enter the grace window (keep the
    /// peer alive, start a timer) unless it's already suspended (double-suspend is a no-op).
    /// Body runs on `graceQueue` (serialized against `resume`/`graceExpired`).
    public func suspend(_ id: String) {
        graceQueue.sync {
            lock.lock(); let held = suspended.contains(id); lock.unlock()
            switch graceDecide(held: held, .suspend) {
            case .hold:
                lock.lock(); suspended.insert(id); lock.unlock()
                let work = DispatchWorkItem { [weak self] in self?.graceExpired(id) }
                lock.lock(); graceTimers[id] = work; lock.unlock()
                graceQueue.asyncAfter(deadline: .now() + .milliseconds(graceMs), execute: work)
                print("[PeerHub] client \(id) suspended (grace \(graceMs)ms)")
            default: break   // .ignore: already held
            }
        }
    }

    /// The grace timer fired without a resume showing up. Tear the peer down for real (unless it
    /// was resumed/cleared out from under the timer in the meantime — `graceDecide` reflects that
    /// via `held`). Runs on `graceQueue` (it IS the timer's DispatchWorkItem block), so it is
    /// serialized against `suspend`/`resume` — never interleaves with a concurrent resume.
    private func graceExpired(_ id: String) {
        lock.lock(); let held = suspended.contains(id); suspended.remove(id); graceTimers[id] = nil; lock.unlock()
        if graceDecide(held: held, .graceExpired) == .teardown {
            print("[PeerHub] client \(id) grace expired -> teardown")
            clientLeft(id)   // the real teardown
        }
    }

    /// The transport told us this client reconnected. Cancel its grace timer and route by mode:
    /// a still-held peer whose mode is `.ice` gets a real ICE restart on the RETAINED peer (Task 15,
    /// `restartICE` below); `.rebuild` tears down + rebuilds a fresh peer; a peer whose grace already
    /// expired is treated as a brand-new join. Body runs on `graceQueue` (serialized against
    /// `suspend`/`graceExpired`) so the state read + routed action are atomic w.r.t. a firing grace
    /// timer.
    /// `claim`: the client is CONNECTING (its join intent) — a reload whose id the relay still held —
    /// and takes control on the connection it resumes, or joins claiming when its grace had expired.
    /// `grid`: what the client said as it joined again (`JoinHello`), applied once the resume has run — its page
    /// already shows its tabs, so no offer waits on it (`clientJoined` applies it before the offer).
    public func resume(_ id: String, mode: ResumeMode, claim: Bool = false, grid: TermGridSize? = nil) {
        var joinedFresh = false
        defer { if let grid, !joinedFresh { channelHub.applyJoinGrid(grid, clientId: id) } }
        graceQueue.sync {
            lock.lock()
            let held = suspended.contains(id)
            suspended.remove(id)
            if let t = graceTimers[id] { t.cancel(); graceTimers[id] = nil }
            lock.unlock()
            // A freshly restarted host can hear peer-suspended before the client's first
            // authenticated handshake. A grace timer alone is not a retained peer: rebuilding
            // media here would skip ChannelHub.register and leave every control message dropped.
            if lock.withLock({ sessions[id] == nil }) {
                joinedFresh = true
                clientJoined(id, claim: claim, grid: grid)
                return
            }
            // A retained peer whose media we released re-establishes nothing on an ICE restart, so
            // an `.ice` resume onto it would resume to a permanently black window. Downgrade to a
            // rebuild, which goes through the path that already works.
            // …and a retained peer still waiting on an ANSWER cannot offer an ICE restart at all.
            lock.lock(); let awaiting = sessions[id]?.awaitingAnswer ?? false; lock.unlock()
            let decided = resumeActionAfterUnansweredOffer(
                resumeActionAfterMediaRelease(
                    graceDecide(held: held, .resume(mode)),
                    mediaReleased: channelHub.mediaWasReleased(clientId: id)
                ),
                awaitingAnswer: awaiting
            )
            switch decided {
            case .restartICE:
                // Task 15: a real ICE restart on the retained peer (no rebuild). Requires the peer's
                // ICE agent to have actually gone live at some point (see PionPeer.restartIce doc) —
                // true here because a `.ice` resume only fires when the client retained a connected
                // PC. If somehow no session is held, fall back to rebuild.
                lock.lock(); let s = sessions[id]; lock.unlock()
                if let s { s.restartIce(); print("[PeerHub] client \(id) resumed (ICE restart)") }
                else { rebuildPeer(id) }
                if claim { channelHub.claim(clientId: id) }
            case .rebuild:
                rebuildPeer(id)
                if claim { channelHub.claim(clientId: id) }
            case .freshJoin:
                // `graceDecide` returns `.freshJoin` whenever the peer was NOT suspended. That's the
                // truly-new case for a CLIENT roam — but a HOST roam also lands here: the host process
                // survives (only its WS + P2P transport dropped), the client never suspended, and the DO
                // re-informs the reconnected host with `peer-resumed(id,"ice")` for every live client. So
                // `sessions[id]` still holds a live retained peer. `clientJoined` would OVERWRITE it
                // (leaking the old PionPeer + its goroutines + its stale encoder-consumer registration)
                // and, because the id stays active, never add the new peer as a video consumer → no
                // video. Recover the retained peer instead when one exists.
                lock.lock(); let retained = sessions[id]; lock.unlock()
                if let retained {
                    // Host-roam: both sides RETAINED their PCs/DTLS (only the host's network moved), so
                    // an ICE restart re-gathers ICE while keeping DTLS on both ends → reconnects. If it
                    // doesn't converge, the client's 5s FSM fallback → rebuild self-heals.
                    if mode == .ice && !retained.awaitingAnswer {
                        retained.restartIce(); print("[PeerHub] client \(id) resumed (ICE restart)")
                    }
                    else { rebuildPeer(id) }
                    if claim { channelHub.claim(clientId: id) }
                } else {
                    joinedFresh = true
                    clientJoined(id, claim: claim, grid: grid)   // truly new (fresh id, or grace expired + torn down)
                }
            default: break   // .hold/.teardown/.ignore can't occur for a .resume event
            }
        }
    }

    /// Drop the stale `PionPeer` (its pion connection is presumed dead) and build+wire a fresh one
    /// for the same client id, rebinding it into ChannelHub so terminal/active state carries over.
    private func rebuildPeer(_ id: String) {
        lock.lock(); let old = sessions[id]; lock.unlock()
        if let old { old.close() }   // ChannelHub.rebindPeer drops the stale delivery sink (it owns videoSlots now)
        let peer = makePeer(id)
        lock.lock(); sessions[id] = peer; lock.unlock()
        if let fast = fastConnection(id) {
            fast.attachMediaPeer(peer); channelHub.replaceMedia(clientId: id)
        } else { channelHub.rebindPeer(clientId: id, peer: peer) }
        peer.startOffer()
        print("[PeerHub] client \(id) resumed (rebuild)")
    }
}


/// Why a recovery-policy update could not be applied. The coordinator turns a thrown error into the
/// non-zero status the ABI reports to the engine, so the controller learns the update did not land.
enum PeerHubRecoveryError: Error {
    case hostGone
    case notApplied
}


extension CaptureFlexFECPolicy {
    /// Decode the tier as it crosses rdev's `pion_on_recovery_policy`.
    ///
    /// The wire numbering is Go's `FlexFECTier` iota — off 0, low 1, medium 2, high 3 — and this
    /// mirrors LLV's own decode in `pionRecoveryPolicyCallback` case for case, including refusing an
    /// unrecognised value rather than defaulting. `adaptive` is deliberately UNREACHABLE here: it is
    /// the POLICY a session is configured with, never a tier the controller resolves to, and
    /// CaptureRecoveryBitrateCoordinator rejects it as an update tier.
    ///
    /// rdev does not otherwise interpret the tier — it reads only the bitrate — but it is decoded
    /// rather than passed through so that a numbering drift between the two sides fails loudly here
    /// instead of silently mislabelling every update the coordinator records.
    init?(rdevTierWireValue raw: Int32) {
        switch raw {
        case 0: self = .off
        case 1: self = .low
        case 2: self = .medium
        case 3: self = .high
        default: return nil
        }
    }
}
